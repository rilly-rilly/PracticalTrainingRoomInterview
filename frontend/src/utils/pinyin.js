const INITIAL_GROUPS = { A, B, C, D, E, F, G, H, J, K, L, M, N, O, P, Q, R, S, T, W, X, Y, Z }

// 构建查找表
const CODE_TO_INITIAL = {}
for (const [initial, chars] of Object.entries(INITIAL_GROUPS)) {
  for (const ch of chars) {
    CODE_TO_INITIAL[ch] = initial
  }
}

/**
 * 获取字符拼音首字母
 */
function initialOfChar(char) {
  if (!char) return ''
  const code = char.codePointAt(0)

  // ASCII
  if (code >= 0x0041 && code <= 0x005A) return char
  if (code >= 0x0061 && code <= 0x007A) return char.toUpperCase()
  if (code >= 0x0030 && code <= 0x0039) return '#'

  // 先查硬编码表（覆盖最常用字）
  if (CODE_TO_INITIAL[char]) return CODE_TO_INITIAL[char]
  if (CHAR_MAP[char]) return CHAR_MAP[char]

  // CJK 核心区：用粗略 fallback —— 返回 '?' 让调用方处理
  if (code >= 0x4E00 && code <= 0x9FA5) {
    return '' // 无法识别，返回空
  }

  return ''
}

/**
 * 获取字符串的拼音首字母串（每个字符取首字母，拼接）
 * 例：张一鸣 -> ZYM ；王雨桐 -> WYT
 */
export function getInitials(str) {
  if (!str) return ''
  let out = ''
  for (const ch of str) {
    const i = initialOfChar(ch)
    if (i) out += i
  }
  return out
}

/**
 * 获取字符串的第一个字符的首字母（用于姓名排序分组）
 */
export function getFirstInitial(str) {
  if (!str) return '#'
  for (const ch of str) {
    const i = initialOfChar(ch)
    if (i) return i
  }
  return '#'
}

/**
 * 判断关键词是否匹配目标（支持姓名/学号/拼音模糊搜索）
 * @param {string} target 目标字符串（姓名、学号等）
 * @param {string} keyword 搜索关键词
 * @returns {boolean}
 */
export function matchKeyword(target, keyword) {
  if (!keyword) return true
  if (!target) return false
  const kw = keyword.trim().toLowerCase()
  const tgt = String(target).toLowerCase()

  // 1. 直接包含匹配
  if (tgt.includes(kw)) return true

  // 2. 拼音首字母匹配（按字符逐个取首字母拼接后再匹配）
  const targetInitials = getInitials(target).toLowerCase()
  if (targetInitials && targetInitials.includes(kw)) return true

  return false
}

// 首字母排序比较器（A-Z）
export function compareByInitial(a, b, getKey = (x) => x, order = 'asc') {
  const ai = getFirstInitial(getKey(a))
  const bi = getFirstInitial(getKey(b))
  let cmp = ai.localeCompare(bi)
  if (cmp !== 0) return order === 'asc' ? cmp : -cmp
  // 首字母相同，用完整字符串排序
  const af = getInitials(getKey(a)).toLowerCase()
  const bf = getInitials(getKey(b)).toLowerCase()
  cmp = af.localeCompare(bf)
  if (cmp !== 0) return order === 'asc' ? cmp : -cmp
  // 再用原始字符兜底
  return order === 'asc' ? getKey(a).localeCompare(getKey(b), 'zh-Hans-CN') : -getKey(a).localeCompare(getKey(b), 'zh-Hans-CN')
}

export default { getInitials, getFirstInitial, matchKeyword, compareByInitial }
